const DICTIONARIES: Record<"en" | "de", Dict> = { en, de };
export type Locale = keyof typeof DICTIONARIES;
const STORAGE_KEY = "clara_locale";

type I18nContextValue = { locale: Locale; t: Dict; setLocale: (locale: Locale) => void };

const I18nContext = createContext<I18nContextValue>({
  locale: "en",
  t: en,
  setLocale: () => undefined,
});

export function I18nProvider({
  children,
  initialLocale = "en",
}: {
  children: ReactNode;
  initialLocale?: Locale;
}) {
  // initialLocale comes from the clara_locale cookie read server-side, so
  // German users get German HTML on first paint - no EN flash. localStorage
  // remains a fallback for sessions from before the cookie existed.
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  useEffect(() => {
    try {
      const hasCookie = document.cookie.includes(`${STORAGE_KEY}=`);
      const stored = window.localStorage.getItem(STORAGE_KEY);
      if (!hasCookie && (stored === "de" || stored === "en")) {
        setLocaleState(stored);
        document.cookie = `${STORAGE_KEY}=${stored};path=/;max-age=31536000;samesite=lax`;
      }
    } catch {
      // storage unavailable; stay on the initial
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
      document.cookie = `${STORAGE_KEY}=${next};path=/;max-age=31536000;samesite=lax`;
    } catch {
      // non-fatal
    }
  }, []);

  return (
    <I18nContext.Provider value={{ locale, t: DICTIONARIES[locale], setLocale }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function LanguageToggle() {
  const { locale, setLocale } = useI18n();
  return (
    <div className="flex items-center rounded-md border text-xs font-medium" role="group" aria-label="Language">
      {(["en", "de"] as const).map((option) => (
        <button
          key={option}
          type="button"
          aria-pressed={locale === option}
          onClick={() => setLocale(option)}
          className={
            "px-2 py-1 uppercase transition-colors " +
            (locale === option
              ? "bg-primary text-primary-foreground rounded-[5px]"
              : "text-muted-foreground hover:text-foreground")
          }
        >
          {option}
        </button>
      ))}
    </div>
  );
}
